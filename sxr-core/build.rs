use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    let csv = include_str!("src/record_kinds.csv");
    let mut rows = csv.lines().filter(|l| !l.trim().is_empty());
    let header = rows.next().expect("csv header");
    let fields: Vec<&str> = header.split('|').collect();
    assert_eq!(
        fields,
        [
            "kind",
            "envelope_kind",
            "primary_entities",
            "required_subject_refs",
            "provenance",
            "allowed_predecessors",
            "required_subject_prefixes",
            "settlement_dependency",
            "authority_class"
        ],
        "record_kinds.csv header must match §5.3b columns"
    );

    let mut kinds: Vec<&str> = Vec::new();
    let mut enum_variants = String::new();
    let mut table_rows = String::new();
    for (idx, line) in rows.enumerate() {
        let cols: Vec<&str> = line.split('|').collect();
        assert_eq!(
            cols.len(),
            9,
            "row {} of record_kinds.csv has {} fields",
            idx + 2,
            cols.len()
        );
        let (
            kind,
            envelope_kind,
            entities,
            subject_refs,
            provenance,
            predecessors,
            prefixes,
            settlement,
            authority,
        ) = (
            cols[0], cols[1], cols[2], cols[3], cols[4], cols[5], cols[6], cols[7], cols[8],
        );
        assert!(
            kind.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '_'),
            "invalid kind {kind:?}"
        );
        kinds.push(kind);
        let variant = kind.split('.').map(capitalize).collect::<String>();
        enum_variants.push_str(&format!("    /// §5.3b `{kind}`.\n    {variant},\n"));
        table_rows.push_str(&format!(
            "    RecordKindDef {{ kind: \"{kind}\", envelope_kind: \"{envelope_kind}\", primary_entities: \"{entities}\", subject_refs: \"{subject_refs}\", provenance: \"{provenance}\", predecessors: \"{predecessors}\", subject_prefixes: \"{prefixes}\", settlement_dependency: \"{settlement}\", authority_class: \"{authority}\" }},\n"
        ));
    }

    let all_variants = kinds
        .iter()
        .map(|k| {
            format!(
                "        RecordKind::{},\n",
                k.split('.').map(capitalize).collect::<String>()
            )
        })
        .collect::<String>();

    let generated = format!(
        "// @generated by build.rs from record_kinds.csv — do not edit by hand.\n\
         // The CSV is the machine-readable transcription of spec §5.3b.\n\n\
         pub struct RecordKindDef {{\n\
         \x20   pub kind: &'static str,\n\
         \x20   pub envelope_kind: &'static str,\n\
         \x20   pub primary_entities: &'static str,\n\
         \x20   pub subject_refs: &'static str,\n\
         \x20   pub provenance: &'static str,\n\
         \x20   pub predecessors: &'static str,\n\
         \x20   pub subject_prefixes: &'static str,\n\
         \x20   pub settlement_dependency: &'static str,\n\
         \x20   pub authority_class: &'static str,\n\
         }}\n\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum RecordKind {{\n{enum_variants}}}\n\n\
         impl RecordKind {{\n\
         \x20   pub const ALL: &'static [RecordKind] = &[\n{all_variants}\
         \x20   ];\n\
         \x20   pub fn as_str(self) -> &'static str {{ TABLE[self as usize].kind }}\n\
         \x20   pub fn def(self) -> &'static RecordKindDef {{ &TABLE[self as usize] }}\n\
         }}\n\n\
         impl std::str::FromStr for RecordKind {{\n\
         \x20   type Err = String;\n\
         \x20   fn from_str(s: &str) -> Result<RecordKind, String> {{\n\
         \x20       Self::ALL.iter().copied().find(|k| k.as_str() == s)\n\
         \x20           .ok_or_else(|| format!(\"unregistered sxr record kind {{}}\", s))\n\
         \x20   }}\n\
         }}\n\n\
         const TABLE: [RecordKindDef; {n}] = [\n{table_rows}];\n",
        n = kinds.len()
    );
    fs::write(Path::new(&out_dir).join("record_kinds_gen.rs"), generated)
        .expect("write generated file");
}

fn capitalize(s: &str) -> String {
    s.split('_')
        .map(|part| {
            let mut c = part.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
