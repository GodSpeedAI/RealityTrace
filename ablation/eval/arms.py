"""M2-A: isolated retrieval-arm execution (frozen §23.1 composition).

Four arms, exactly as frozen:

    A = SQL + FTS
    B = SQL + FTS + vector
    C = SQL + FTS + graph
    D = SQL + FTS + graph + vector

Each arm receives ONLY the retrieval capabilities assigned to it. The arm
context is a self-describing artifact: a capability manifest plus one content
section per capability. Any context whose manifest or sections disagree with
the arm definition is rejected at the boundary (build and validate), so no
arm can accidentally receive context generated by another arm.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field

SQL = "sql"
FTS = "fts"
VECTOR = "vector"
GRAPH = "graph"

ALL_CAPABILITIES = (SQL, FTS, VECTOR, GRAPH)

# Frozen arm definitions (§23.1). SQL is always included: it is the run's own
# record (structured evidence), not a strategy.
ARMS: dict[str, frozenset[str]] = {
    "A": frozenset({SQL, FTS}),
    "B": frozenset({SQL, FTS, VECTOR}),
    "C": frozenset({SQL, FTS, GRAPH}),
    "D": frozenset({SQL, FTS, GRAPH, VECTOR}),
}

ARM_NAMES = ("A", "B", "C", "D")


class ArmViolation(Exception):
    """Raised when an arm receives context outside its assigned capabilities."""


@dataclass(frozen=True)
class RetrievalContext:
    """The retrieval material handed to an evaluator for one (case, arm).

    self-describing: `manifest` lists the capabilities whose sections are
    present in `sections`. Nothing outside the arm's capability set may be
    present, and every assigned capability must contribute a section.
    """

    arm: str
    case_id: str
    sections: dict[str, str] = field(default_factory=dict)

    @property
    def manifest(self) -> tuple[str, ...]:
        return tuple(sorted(self.sections.keys()))

    def fingerprint(self) -> str:
        payload = {
            "arm": self.arm,
            "case_id": self.case_id,
            "sections": dict(sorted(self.sections.items())),
        }
        blob = hashlib.sha256(repr(payload).encode()).hexdigest()
        return blob

    def to_dict(self) -> dict:
        return {
            "arm": self.arm,
            "case_id": self.case_id,
            "manifest": list(self.manifest),
            "sections": dict(sorted(self.sections.items())),
        }

    @staticmethod
    def from_dict(d: dict) -> "RetrievalContext":
        return RetrievalContext(arm=d["arm"], case_id=d["case_id"],
                                sections=dict(d.get("sections", {})))


def validate_arm_context(ctx: RetrievalContext) -> None:
    """Reject any context that does not match its declared arm exactly.

    - every section capability must be assigned to the arm, and
    - every capability assigned to the arm must contribute a section, and
    - the arm itself must be one of the frozen four.

    This is the enforcement boundary used both at context build time and at
    the evaluator boundary, so cross-arm context can never be delivered.
    """
    if ctx.arm not in ARMS:
        raise ArmViolation(f"unknown arm {ctx.arm!r}")
    allowed = ARMS[ctx.arm]
    present = set(ctx.sections.keys())
    forbidden = present - allowed
    if forbidden:
        raise ArmViolation(
            f"arm {ctx.arm} received capability not assigned: "
            f"{sorted(forbidden)}")
    missing = allowed - present
    if missing:
        raise ArmViolation(
            f"arm {ctx.arm} missing assigned capability sections: "
            f"{sorted(missing)}")


def build_arm_context(arm: str, case_id: str, store: dict[str, str]) -> RetrievalContext:
    """Compose a context using ONLY the arm's assigned capabilities.

    `store` is the shared retrieval store keyed by capability (sql, fts,
    vector, graph). Only the capabilities assigned to `arm` are read from it.
    """
    ctx = RetrievalContext(arm=arm, case_id=case_id)
    for cap in sorted(ARMS[arm]):
        if cap not in store:
            raise ArmViolation(f"store has no {cap!r} section for {case_id}")
        ctx.sections[cap] = store[cap]
    validate_arm_context(ctx)
    return ctx
